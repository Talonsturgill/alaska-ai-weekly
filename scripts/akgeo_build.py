#!/usr/bin/env python3
"""Build video-engine/src/lib/akgeo_data.ts, the TRUE Alaska outline, from a state GeoJSON.

WHY (machine pass 2026-11-26; queue alaska-map-true-geodata, repeat 1). lib/akmap.ts's AK_PATH is a
hand-placed stylised outline, and episodes keep reaching for it, or hand-typing their own points, when a
film needs a map: an 11-xx Point Lay pin and an Anchorage to Seward route landed in the wrong places,
and on 11-26 seat 3 called the S2/S5/S6 Alaska "a crude polygon with no Aleutians". This writes the real
coastline, projected and simplified once, plus the projection constants, so lib/akgeo.tsx can draw it and
place any lon/lat (a town, a route) where it really is.

Source: Natural Earth 10m admin-1 Alaska (public domain), as committed in the sibling carousel repo's
assets/geo/alaska-state.geo.json. Read-only use of that file; pass its path. Projection: Alaska Albers
equal-area conic (EPSG:3338: standard parallels 55 and 65 N, origin 50 N 154 W), longitudes east of 180
wrapped to the west so the Aleutians stay one chain. Rings are Douglas-Peucker simplified at TOL in the
1000 px wide draw box, and islands under MIN_AREA square px dropped, which keeps the Aleutian chain,
Kodiak, the Pribilofs and St Lawrence and drops rocks.

    python3 scripts/akgeo_build.py /home/user/alaskaaicarousels/assets/geo/alaska-state.geo.json
    python3 scripts/akgeo_build.py --check    # the committed data parses and reproduces its own box
"""
import json
import math
import os
import re
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(REPO, "video-engine", "src", "lib", "akgeo_data.ts")
W = 1000.0
TOL = 0.9
MIN_AREA = 6.0
LAT1, LAT2, LAT0, LON0 = 55.0, 65.0, 50.0, -154.0


def albers(lon, lat):
    """Spherical Alaska Albers, unit sphere; returns (x, y) with +y north."""
    r = math.radians
    n = (math.sin(r(LAT1)) + math.sin(r(LAT2))) / 2
    c = math.cos(r(LAT1)) ** 2 + 2 * n * math.sin(r(LAT1))
    rho0 = math.sqrt(c - 2 * n * math.sin(r(LAT0))) / n
    if lon > 0:
        lon -= 360.0
    rho = math.sqrt(c - 2 * n * math.sin(r(lat))) / n
    th = n * r(lon - LON0)
    return rho * math.sin(th), rho0 - rho * math.cos(th)


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    if pts[0] == pts[-1]:
        # a closed ring: its chord is a point, so split it at the vertex farthest from the start
        far = max(range(len(pts)), key=lambda i: math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]))
        if far == 0:
            return pts[:1]
        return dp(pts[:far + 1], tol)[:-1] + dp(pts[far:], tol)
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (ax, ay), (bx, by) = pts[a], pts[b]
        dx, dy = bx - ax, by - ay
        L = math.hypot(dx, dy) or 1e-9
        best, bi = -1.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / L
            if d > best:
                best, bi = d, i
        if best > tol:
            keep[bi] = True
            stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]


def area(pts):
    return abs(sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]))) / 2


def build(src):
    g = json.load(open(src))["features"][0]["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    rings = [[albers(lon, lat) for lon, lat in poly[0]] for poly in polys]
    xs = [x for r in rings for x, _ in r]
    ys = [y for r in rings for _, y in r]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    k = W / (x1 - x0)
    H = (y1 - y0) * k
    out = []
    for r in rings:
        pts = [((x - x0) * k, (y1 - y) * k) for x, y in r]
        if area(pts) < MIN_AREA:
            continue
        s = dp(pts, TOL)
        if len(s) >= 4:
            out.append(s)
    out.sort(key=area, reverse=True)
    d = " ".join("M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in r[:-1]) + " Z" for r in out)
    return d, {"x0": x0, "y1": y1, "k": k, "w": W, "h": round(H, 1)}, len(out), sum(len(r) for r in out)


def write(src):
    d, box, nrings, npts = build(src)
    body = f"""// GENERATED by scripts/akgeo_build.py from Natural Earth 10m Alaska (public domain). Never edit by hand;
// rerun the script. {nrings} rings, {npts} points, Alaska Albers (EPSG:3338 parameters) in a {box['w']:g} x {box['h']:g} box.
export const AK_GEO_BOX = {{w: {box['w']:g}, h: {box['h']:g}}};
/** projection constants: draw x = (albersX - x0) * k, draw y = (y1 - albersY) * k (unit-sphere Albers) */
export const AK_GEO_FIT = {{x0: {box['x0']!r}, y1: {box['y1']!r}, k: {box['k']!r}}};
export const AK_GEO_ALBERS = {{lat1: {LAT1:g}, lat2: {LAT2:g}, lat0: {LAT0:g}, lon0: {LON0:g}}};
export const AK_GEO_PATH =
  '{d}';
"""
    with open(OUT, "w") as fh:
        fh.write(body)
    print(f"akgeo_build: wrote {os.path.relpath(OUT, REPO)} ({nrings} rings, {npts} points, {len(d)} chars)")
    return 0


def check():
    """The committed data parses, every point sits inside its box, and the projection reproduces known
    places: Utqiagvik is the northernmost of the gazetteer towns, Ketchikan the south-eastern corner,
    Adak far west, and Anchorage lands on the land path's interior side of Cook Inlet."""
    txt = open(OUT).read()
    box = json.loads(re.search(r"AK_GEO_BOX = (\{[^}]*\})", txt).group(1).replace("w:", '"w":').replace("h:", '"h":'))
    fit = re.search(r"AK_GEO_FIT = \{x0: ([-\d.e]+), y1: ([-\d.e]+), k: ([-\d.e]+)\}", txt)
    x0, y1, k = map(float, fit.groups())
    d = re.search(r"AK_GEO_PATH =\s*'([^']*)'", txt).group(1)
    pts = [tuple(map(float, p.split(","))) for p in re.findall(r"-?\d+\.\d,-?\d+\.\d", d)]
    rings = d.count("M")
    assert pts and all(-1 <= x <= box["w"] + 1 and -1 <= y <= box["h"] + 1 for x, y in pts), "a point outside the box"

    def proj(lon, lat):
        x, y = albers(lon, lat)
        return (x - x0) * k, (y1 - y) * k
    ut, ke, ad, an = proj(-156.7886, 71.2906), proj(-131.6461, 55.3422), proj(-176.6581, 51.88), proj(-149.9003, 61.2181)
    assert ut[1] < 40, f"Utqiagvik not at the top: {ut}"
    assert ke[0] > box["w"] * 0.9, f"Ketchikan not at the east edge: {ke}"
    assert ad[0] < box["w"] * 0.2 and ad[1] > box["h"] * 0.8, f"Adak not far south-west: {ad}"
    assert rings >= 40, f"only {rings} rings: the Aleutian chain was dropped"
    print(f"akgeo_build --check: PASS ({rings} rings, {len(pts)} points in {box['w']:g} x {box['h']:g}; "
          f"Utqiagvik {ut[0]:.0f},{ut[1]:.0f}  Anchorage {an[0]:.0f},{an[1]:.0f}  Ketchikan {ke[0]:.0f},{ke[1]:.0f}  "
          f"Adak {ad[0]:.0f},{ad[1]:.0f})")
    return 0


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[:1] == ["--check"]:
        sys.exit(check())
    if not a:
        print(__doc__)
        sys.exit(2)
    sys.exit(write(a[0]))
