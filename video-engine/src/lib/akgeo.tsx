const RAD = Math.PI / 180;
const N = (Math.sin(AK_GEO_ALBERS.lat1 * RAD) + Math.sin(AK_GEO_ALBERS.lat2 * RAD)) / 2;
const C = Math.cos(AK_GEO_ALBERS.lat1 * RAD) ** 2 + 2 * N * Math.sin(AK_GEO_ALBERS.lat1 * RAD);
const RHO0 = Math.sqrt(C - 2 * N * Math.sin(AK_GEO_ALBERS.lat0 * RAD)) / N;

export interface AkFit {
  /** top-left of the drawn box in the parent's px */
  x?: number;
  y?: number;
  /** drawn width in px; the height follows the box's aspect (AK_GEO_BOX.h / AK_GEO_BOX.w) */
  w?: number;
}

/** A lon/lat (WGS84 degrees; east longitudes wrap west so the Aleutians stay one chain) in the parent's px
 *  for an outline drawn at fit. The same projection and fit akgeo_build used for the coastline. */
export function akProject(lon: number, lat: number, fit: AkFit = {}): [number, number] {
  const {x = 0, y = 0, w = AK_GEO_BOX.w} = fit;
  const L = lon > 0 ? lon - 360 : lon;
  const rho = Math.sqrt(C - 2 * N * Math.sin(lat * RAD)) / N;
  const th = N * (L - AK_GEO_ALBERS.lon0) * RAD;
  const ax = rho * Math.sin(th), ay = RHO0 - rho * Math.cos(th);
  const s = w / AK_GEO_BOX.w;
  return [x + (ax - AK_GEO_FIT.x0) * AK_GEO_FIT.k * s, y + (AK_GEO_FIT.y1 - ay) * AK_GEO_FIT.k * s];
}

/** the drawn height for a width */
export const akHeight = (w: number) => (w * AK_GEO_BOX.h) / AK_GEO_BOX.w;

export const AlaskaOutline: React.FC<{
  x?: number;
  y?: number;
  w?: number;
  fill?: string;
  stroke?: string;
  /** stroke width in the PARENT's px (it does not scale with w) */
  strokeWidth?: number;
  /** a darker offset copy under the land, px; 0 for none */
  shadow?: number;
  shadowColor?: string;
  /** names from AK_TOWNS to pin, drawn as dots (labels are the episode's own, placed with akProject) */
  towns?: string[];
  townR?: number;
  townColor?: string;
  /** an id for the clipPath, so terrain can be clipped inside the land: clipPath={`url(#${clipId})`} */
  clipId?: string;
  opacity?: number;
}> = ({x = 0, y = 0, w = 1000, fill = '#E7E2D2', stroke = '#1B1A22', strokeWidth = 3, shadow = 6, shadowColor = '#000000',
  towns = [], townR = 7, townColor = '#E2563E', clipId, opacity = 1}) => {
  const s = w / AK_GEO_BOX.w;
  const tf = `translate(${x} ${y}) scale(${s})`;
  return (
    <g opacity={opacity}>
      {clipId && (
        <defs>
          <clipPath id={clipId}><path d={AK_GEO_PATH} transform={tf} /></clipPath>
        </defs>
      )}
      {shadow > 0 && <path d={AK_GEO_PATH} transform={`translate(${x + shadow * 0.5} ${y + shadow}) scale(${s})`} fill={shadowColor} opacity={0.22} />}
      <path d={AK_GEO_PATH} transform={tf} fill={fill} stroke={stroke} strokeWidth={strokeWidth / s} strokeLinejoin="round" />
      {towns.map((t) => {
        const ll = AK_TOWNS[t];
        if (!ll) return null;
        const [px, py] = akProject(ll[0], ll[1], {x, y, w});
        return <circle key={t} cx={px} cy={py} r={townR} fill={townColor} stroke={stroke} strokeWidth={2} />;
      })}
    </g>
  );
};
