//
//   <AlaskaOutline x={90} y={600} w={900} fill="#E7E2D2" stroke={INK} towns={['Anchorage', 'Bethel']} />
//   const [px, py] = akProject(-162.6, 69.7, {x: 90, y: 600, w: 900});   // Point Lay, a cited lon/lat
